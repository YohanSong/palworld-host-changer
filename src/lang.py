_HERE = os.path.dirname(sys.executable if getattr(sys, "frozen", False) else os.path.abspath(__file__))
_PREF = os.path.join(_HERE, "lang.txt")


def system_lang():
    try:
        primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
    except Exception:
        return "en"
    return {0x12: "ko", 0x04: "zh", 0x11: "ja"}.get(primary, "en")


def load_lang():
    try:
        code = open(_PREF, encoding="ascii").read().strip()
        if code in S:
            return code
    except Exception:
        pass
    return system_lang()


def save_lang(code):
    try:
        with open(_PREF, "w", encoding="ascii") as fh:
            fh.write(code)
    except Exception:
        pass  # read-only folder: the choice just isn't remembered


current = load_lang()


def t(key, **fmt):
    text = S[current].get(key) or S["en"][key]
    return text.format(**fmt) if fmt else text


